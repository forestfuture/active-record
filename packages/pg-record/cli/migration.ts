// A generated migration's SQL, in Postgres's own types: UUID keys made in code, or identity keys Postgres makes.
import {
  indexName,
  migrationPlan,
  type ColumnArg,
  type MigrationChange,
  type MigrationResult,
} from "@forestfuture/active-record/cli";

type SqlResult = { ok: true; sql: string } | { ok: false; error: string };

// The words Postgres reserves, even as a column's name (pg_get_keywords, categories R and T).
const keywords = new Set(
  (
    "all analyse analyze and any array as asc asymmetric authorization binary both case cast check " +
    "collate collation column concurrently constraint create cross current_catalog current_date " +
    "current_role current_schema current_time current_timestamp current_user default deferrable " +
    "desc distinct do else end except false fetch for foreign freeze from full grant group having " +
    "ilike in initially inner intersect into is isnull join lateral leading left like limit " +
    "localtime localtimestamp natural not notnull null offset on only or order outer overlaps " +
    "placing primary references returning right select session_user similar some symmetric " +
    "system_user table tablesample then to trailing true union unique user using variadic verbose " +
    "when where window with"
  ).split(" "),
);

/** A name as SQL: quoted only when Postgres reserves it, so migrations stay readable. */
function identifier(name: string): string {
  return keywords.has(name) ? `"${name}"` : name;
}

/** The key a table gets: a UUID made in code, as `generateId` makes it (ADR-0013), or Postgres's identity. */
const keyColumn = (integerId: boolean | undefined) =>
  integerId ? "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "id UUID PRIMARY KEY";

/** The key type a reference to a table the migrations don't make yet takes: the generators' own. */
const guessedKeyType = "UUID";

const sqlTypes: Record<Exclude<ColumnArg["type"], "references">, string> = {
  string: "TEXT",
  // An integer attribute holds any safe integer, which INTEGER's 32 bits can't.
  integer: "BIGINT",
  real: "DOUBLE PRECISION",
  boolean: "BOOLEAN",
  datetime: "TIMESTAMPTZ",
  json: "JSONB",
};

/** A default as a SQL literal: `TRUE`, `1.5`, `'it''s'`. */
function literal(value: string | number | boolean): string {
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  return typeof value === "number" ? String(value) : `'${value.replaceAll("'", "''")}'`;
}

/** A column's definition, as `CREATE TABLE` and `ADD COLUMN` write it. */
function definition(
  column: ColumnArg,
  keys: ReadonlyMap<string, string>,
  notNull: boolean,
): string {
  const name = identifier(column.name);
  const parts = [name];
  if (column.type === "references") {
    parts.push((keys.get(column.references!) ?? guessedKeyType).toUpperCase());
  } else parts.push(sqlTypes[column.type]);
  if (notNull) parts.push("NOT NULL");
  if (column.type === "references") parts.push(`REFERENCES ${identifier(column.references!)} (id)`);
  else if (column.default !== undefined) parts.push(`DEFAULT ${literal(column.default)}`);
  return parts.join(" ");
}

/** `CREATE [UNIQUE] INDEX` for each indexed column. */
function indexes(table: string, columns: readonly ColumnArg[]): string {
  return columns
    .filter((column) => column.index !== "none")
    .map((column) => {
      const unique = column.index === "unique" ? "UNIQUE " : "";
      const on = `${identifier(table)} (${identifier(column.name)})`;
      return `CREATE ${unique}INDEX ${indexName(table, column.name)} ON ${on};\n`;
    })
    .join("");
}

/** `CREATE TABLE`, with its key, columns, timestamps and indexes. */
function createTable(
  table: string,
  columns: readonly ColumnArg[],
  keys: ReadonlyMap<string, string>,
  options: MigrationChange["options"],
): string {
  const lines = [keyColumn(options.integerId)];
  for (const column of columns) lines.push(definition(column, keys, column.notNull));
  if (options.timestamps !== false)
    lines.push("created_at TIMESTAMPTZ NOT NULL", "updated_at TIMESTAMPTZ NOT NULL");
  return `CREATE TABLE ${identifier(table)} (\n  ${lines.join(",\n  ")}\n);\n${indexes(table, columns)}`;
}

/**
 * `ADD COLUMN` for each column. Postgres adds a NOT NULL column without a default to an empty
 * table, and refuses it then for a table with rows; a reference added later can be null.
 */
function addColumns(
  table: string,
  columns: readonly ColumnArg[],
  keys: ReadonlyMap<string, string>,
): string {
  const added = columns
    .map((column) => {
      const notNull = column.type !== "references" && column.notNull;
      return `ALTER TABLE ${identifier(table)} ADD COLUMN ${definition(column, keys, notNull)};\n`;
    })
    .join("");
  return added + indexes(table, columns);
}

/** `DROP COLUMN` for each column; Postgres drops its indexes with it. */
function removeColumns(table: string, columns: readonly ColumnArg[]): string {
  return columns
    .map((column) => `ALTER TABLE ${identifier(table)} DROP COLUMN ${identifier(column.name)};\n`)
    .join("");
}

/** The SQL for a migration named `name` with `columns`, or why it can't be written. */
function migrationFor({ name, columns, keys, options }: MigrationChange): SqlResult {
  const plan = migrationPlan(name);
  if (plan.kind === "empty") {
    return columns.length > 0
      ? {
          ok: false,
          error: `${name}: columns only go with Create…, Add…To… or Remove…From… migrations`,
        }
      : { ok: true, sql: "-- Write the migration's SQL here.\n" };
  }
  if (columns.length === 0 && plan.kind !== "create") {
    return { ok: false, error: `${name}: name the columns to ${plan.kind} (sku:string)` };
  }
  if (plan.kind === "create")
    return { ok: true, sql: createTable(plan.table, columns, keys, options) };
  const sql =
    plan.kind === "remove"
      ? removeColumns(plan.table, columns)
      : addColumns(plan.table, columns, keys);
  return { ok: true, sql };
}

/** Notes for references to tables the migrations don't make yet: their key type is a guess. */
function referenceNotes(
  columns: readonly ColumnArg[],
  keys: ReadonlyMap<string, string>,
): string[] {
  return columns
    .filter((column) => column.type === "references" && !keys.has(column.references!))
    .map(
      (column) =>
        `${column.references} isn't in the migrations yet, so ${column.name} is ${guessedKeyType}`,
    );
}

/** A migration's SQL, for Postgres, with a note for each key type it guessed. */
export function migration(change: MigrationChange): MigrationResult {
  const result = migrationFor(change);
  // A removed reference's type isn't written, so nothing was guessed.
  if (!result.ok || migrationPlan(change.name).kind === "remove") return result;
  const notes = referenceNotes(change.columns, change.keys);
  return notes.length === 0 ? result : { ...result, notes };
}
