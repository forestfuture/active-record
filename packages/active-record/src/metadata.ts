// Attribute metadata: each attribute's type, column and default, resolved from its spec.
import { attributeName, type AttributeAlias } from "./attribute-aliases.ts";
import { type AnyCustomType, type CustomType, isCustomType } from "./custom-types.ts";
import { copiedKeys } from "./spec-keys.ts";
import type { EnumNames, EnumValues, IntegerEnum, TextEnum } from "./enum-values.ts";
import type { EpochStorage } from "./epoch-storage.ts";
import { InvalidModel, UnknownAttribute } from "./errors.ts";
import type { ModelClass } from "./model.ts";
import { underscore } from "./naming.ts";
import type { SecurePasswordDeclaration, SecurePasswordOptions } from "./secure-passwords.ts";
import { isTokenOnInitialize, tokenFor, type SecureTokenOptions } from "./secure-tokens.ts";

export type AttributeType =
  | "string"
  | "integer"
  | "real"
  | "decimal"
  | "boolean"
  | "datetime"
  | "date"
  | "time"
  | "json"
  | "binary";

/** An attribute's spec written out: its type, and optionally nullability, column and default. */
export interface SpecObject {
  /** A built-in type's name, or a type `defineType` made (#20). */
  type: AttributeType | AnyCustomType;
  null?: boolean;
  column?: string;
  /** A `datetime` held as a Unix epoch integer, as Drizzle's timestamp modes write it (#73). */
  storage?: EpochStorage;
  /** A decimal's most digits in all, as `NUMERIC(10, 2)`'s 10; without a scale, its scale is 0 (#398). */
  precision?: number;
  /** A decimal's digits after the point, as `NUMERIC(10, 2)`'s 2: a cast value is rounded to them (#398). */
  scale?: number;
  /** Evaluated at `build()`, e.g. `() => new Date()`. */
  default?: () => unknown;
  /**
   * Made by the Model's `generateId` when not given, where a default would run: an
   * app-generated key (#99). Generated ids are strings, so only a string attribute has one.
   */
  generateId?: boolean;
  /** Its only values, by name, and what each is stored as (#340). */
  enum?: EnumValues;
  /** A word before each enum name in its methods' names: the attribute's name for `true` (#340). */
  prefix?: boolean | string;
  /** A word after each enum name in its methods' names: the attribute's name for `true` (#340). */
  suffix?: boolean | string;
  /** `false` to give the Model no scope for each enum name (#340). */
  scopes?: boolean;
  /** `false` to give records no predicate or `saveAs…` setter for each enum name (#340). */
  instanceMethods?: boolean;
  /**
   * Validates an enum's value instead of refusing an unknown one when it's assigned: a
   * record holding another value, or null unless `allowNull`, is invalid.
   */
  validate?: EnumValidation;
  /**
   * An attribute that isn't a column (#356): cast and tracked like one, never read from a row or
   * written to one, and refused in queries.
   */
  virtual?: boolean;
  /**
   * A virtual password kept as its digest, in the column of the attribute named for it with
   * `Digest` (#355): `true`, or its options.
   */
  securePassword?: true | SecurePasswordOptions;
  /**
   * A random token, generated for a new record that has none, and regenerated by
   * `regenerate…()` (#355): `true`, or its options. Only a string has one.
   */
  secureToken?: boolean | SecureTokenOptions;
}

/** How an enum's value is validated: `true`, or `{ allowNull: true }` to let it be null. */
type EnumValidation = boolean | { readonly allowNull?: boolean };

/** Where a string attribute's value comes from when it isn't given: a default or `generateId`, never both. */
export type ValueSource =
  | { default?: () => unknown; generateId?: false }
  | { default?: never; generateId: true };

/** An attribute that isn't an enum: no type but a string or an integer has one (#340). */
type NoEnum = {
  enum?: never;
  prefix?: never;
  suffix?: never;
  scopes?: never;
  instanceMethods?: never;
  validate?: never;
};

/** An attribute that isn't a decimal: only a decimal has a precision and a scale (#398). */
type NoDigits = { precision?: never; scale?: never };

/** An attribute that isn't a string: only a string has a secure token (#355). */
type NoToken = { secureToken?: never };

/** The spec's keys that only some types have, each written by the type's own branch below. */
type PerTypeKeys =
  | "type"
  | "generateId"
  | "storage"
  | "enum"
  | "precision"
  | "scale"
  | "secureToken";

export type AttributeSpec = AttributeType | AnyCustomType | (SpecObjectByType & Placement);

/** A column, or a virtual attribute, which has none (#356). */
type Placement = { virtual?: false } | { virtual: true; column?: never };

/** A spec written out, by its type: the keys each type may have. */
type SpecObjectByType =
  | (Omit<SpecObject, "default" | PerTypeKeys> & {
      type: "string";
      storage?: never;
      enum?: TextEnum;
      secureToken?: boolean | SecureTokenOptions;
    } & ValueSource &
      NoDigits)
  | (Omit<SpecObject, PerTypeKeys> &
      NoDigits &
      NoToken & {
        type: "integer";
        generateId?: false;
        storage?: never;
        enum?: IntegerEnum;
      })
  | (Omit<SpecObject, PerTypeKeys> &
      NoEnum &
      NoDigits &
      NoToken & {
        type: Exclude<AttributeType, "string" | "integer" | "datetime" | "decimal">;
        generateId?: false;
        storage?: never;
      })
  | (Omit<SpecObject, PerTypeKeys> &
      NoEnum &
      NoToken & {
        type: "decimal";
        generateId?: false;
        storage?: never;
        precision?: number;
        scale?: number;
      })
  | (Omit<SpecObject, Exclude<PerTypeKeys, "storage">> &
      NoEnum &
      NoDigits &
      NoToken & {
        type: "datetime";
        generateId?: false;
      })
  | (Omit<SpecObject, PerTypeKeys> &
      NoEnum &
      NoDigits &
      NoToken & {
        type: AnyCustomType;
        generateId?: false;
        storage?: never;
      });

export type AttributeSpecs = Record<string, AttributeSpec>;

/** What `define` takes: attribute specs, aliases of them (#509), and secure passwords (#355). */
export type DeclaredAttributes = Record<
  string,
  AttributeSpec | AttributeAlias | SecurePasswordDeclaration
>;

/**
 * `A`, with any key a spec doesn't have typed `never`, so a misspelled one (`nul: false`) is a
 * compile error: a generic parameter skips TypeScript's own check for unknown keys (#102).
 */
export type ExactSpecs<A> = {
  [K in keyof A]: A[K] extends AnyCustomType
    ? A[K]
    : A[K] extends { aliasOf: string }
      ? A[K] & Record<Exclude<keyof A[K], "aliasOf">, never>
      : A[K] extends { securePassword: unknown; type?: never }
        ? A[K] &
            ExactSecurePassword<A[K]["securePassword"]> &
            Record<Exclude<keyof A[K], "securePassword">, never>
        : A[K] extends object
          ? A[K] & Record<Exclude<keyof A[K], keyof SpecObject>, never>
          : A[K];
};

/** A secure password's `securePassword`, with any option it doesn't have typed `never` (#355). */
type ExactSecurePassword<P> = {
  securePassword: P extends true
    ? true
    : P & Record<Exclude<keyof P, keyof SecurePasswordOptions>, never>;
};

/** An attribute's resolved metadata. */
export interface AttributeDefinition {
  /** Its built-in type: for a custom type, the type it's stored as. */
  type: AttributeType;
  /** The type `defineType` made, whose values it holds, kept as `type`'s (#20). */
  customType?: AnyCustomType;
  column: string;
  default?: () => unknown;
  generateId?: true;
  storage?: EpochStorage;
  precision?: number;
  scale?: number;
  enum?: EnumValues;
  prefix?: boolean | string;
  suffix?: boolean | string;
  scopes?: boolean;
  instanceMethods?: boolean;
  validate?: EnumValidation;
  /** Not a column: never read or written, and refused in queries (#356). */
  virtual?: true;
  /** A secure password, kept as its digest (#355). */
  securePassword?: true | SecurePasswordOptions;
  /** A secure token, generated for a new record (#355). */
  secureToken?: true | SecureTokenOptions;
}

/** The JavaScript value an attribute of a built-in type holds: a `Date` for a `datetime`. */
export type BuiltInValue<T extends AttributeType> = T extends "string"
  ? string
  : T extends "integer" | "real"
    ? number
    : T extends "boolean"
      ? boolean
      : T extends "datetime"
        ? Date
        : T extends "binary"
          ? Uint8Array
          : T extends "decimal" | "date" | "time"
            ? string
            : unknown;

/** A type's JavaScript value: a built-in type's, or a custom type's own (#20). */
type ValueOf<T> = T extends AttributeType
  ? BuiltInValue<T>
  : T extends CustomType<infer V, AttributeType>
    ? V
    : never;

/** A spec's value, not null: an enum's names (#340), or its type's JavaScript value. */
type SpecValue<S> = S extends { enum: infer E extends EnumValues }
  ? EnumNames<E>
  : S extends { type: infer T }
    ? ValueOf<T>
    : never;

type AttributeValue<S> = S extends AttributeType | AnyCustomType
  ? ValueOf<S> | null
  : S extends { type: unknown; null: false }
    ? SpecValue<S>
    : S extends { type: unknown }
      ? SpecValue<S> | null
      : never;

export type AttributeProperties<A extends AttributeSpecs> = {
  -readonly [K in keyof A]: AttributeValue<A[K]>;
};

/** A spec written out: a type alone (a name, or a custom type) as `{ type }`. */
export function specObjectOf(spec: AttributeSpec): SpecObject {
  return typeof spec === "string" || isCustomType(spec) ? { type: spec } : spec;
}

/** Resolves an attribute's spec into its type, column and default. */
export function define(name: string, spec: AttributeSpec): AttributeDefinition {
  if (typeof spec === "string") return { type: spec, column: underscore(name) };
  if (isCustomType(spec)) return { ...resolvedType(spec), column: underscore(name) };
  if (spec.virtual === true) return defineVirtual(name, spec);
  return {
    ...resolvedType(spec.type),
    column: spec.column ?? underscore(name),
    ...copiedKeys(spec),
  };
}

/**
 * A virtual attribute's definition (#356): no column (`""`, unless one was given, which a Model's
 * check refuses), and non-null only with a default.
 */
function defineVirtual(name: string, spec: SpecObject): AttributeDefinition {
  const problem = virtualNullProblem(name, spec);
  if (problem !== undefined) throw new InvalidModel(problem);
  return { ...resolvedType(spec.type), column: spec.column ?? "", ...copiedKeys(spec) };
}

/** A virtual attribute declared non-null with no default, which would read as null (#356). */
export function virtualNullProblem(
  where: string,
  spec: Pick<SpecObject, "null" | "default">,
): string | undefined {
  return spec.null === false && spec.default === undefined
    ? `${where} is virtual and null: false, so it needs a default`
    : undefined;
}

/** A spec's type as a definition holds it: a custom type as the type it's stored as, and itself. */
function resolvedType(type: SpecObject["type"]): Pick<AttributeDefinition, "type" | "customType"> {
  return isCustomType(type) ? { type: type.storedAs, customType: type } : { type };
}

/** Looks up a declared attribute, or the one an alias names; throws `UnknownAttribute` for any other name. */
export function attributeOf(
  model: {
    readonly name: string;
    readonly attributeDefinitions: ModelClass["attributeDefinitions"];
    readonly attributeAliases?: ModelClass["attributeAliases"];
  },
  name: string,
): AttributeDefinition {
  const attribute = model.attributeDefinitions.get(attributeName(model, name));
  if (attribute === undefined) {
    throw new UnknownAttribute(`${model.name} has no attribute "${name}"`);
  }
  return attribute;
}

/**
 * Looks up an attribute a query reads or writes as a column: `UnknownAttribute` for a name the
 * Model doesn't have, or a virtual attribute, which has none (#356).
 */
export function columnOf(
  model: Parameters<typeof attributeOf>[0],
  name: string,
): AttributeDefinition {
  const attribute = attributeOf(model, name);
  if (attribute.virtual === true) {
    throw new UnknownAttribute(
      `${model.name}.${name} is a virtual attribute, which has no column to query`,
    );
  }
  return attribute;
}

/** The attribute names mapped to `column` (usually one; none if the column isn't declared). */
export function attributesForColumn(model: ModelClass, column: string): string[] {
  return [...model.attributeDefinitions]
    .filter(([, definition]) => definition.column === column)
    .map(([name]) => name);
}

/** `undefined` would silently store NULL, so writing it throws `TypeError` (use `null`). */
export function requireDefined(model: ModelClass, name: string, value: unknown): void {
  if (value === undefined) {
    throw new TypeError(`${model.name}: got undefined for "${name}"; use null to store NULL`);
  }
}

/**
 * The initial values of every attribute not in `given` that has one, made now: each one's
 * `default`, for a generated id, the Model's `generateId(name)`, and for a secure token generated
 * as a record is built, a new token (#355).
 */
export function initialValues(model: ModelClass, given: object = {}): [string, unknown][] {
  return [...model.attributeDefinitions]
    .filter(([name, definition]) => !(name in given) && hasInitialValue(definition))
    .map(([name, definition]) => [name, initialValue(model, name, definition)]);
}

function initialValue(model: ModelClass, name: string, definition: AttributeDefinition): unknown {
  if (definition.generateId) return model.generateId(name);
  return isTokenOnInitialize(definition) ? tokenFor(definition) : definition.default!();
}

/** Whether an attribute gets a value when none is given: from its `default`, `generateId`, or a token. */
function hasInitialValue(definition: AttributeDefinition): boolean {
  return (
    definition.generateId === true ||
    definition.default !== undefined ||
    isTokenOnInitialize(definition)
  );
}
