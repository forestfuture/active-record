import { inspect } from "node:util";
import { afterAll, afterEach, beforeAll, describe, expect, test } from "vite-plus/test";
import {
  InvalidForeignKey,
  Model,
  RecordNotUnique,
  CheckViolation,
} from "../../../packages/active-record/src/index.ts";
import {
  connect,
  type Database,
} from "../../../packages/active-record/src/adapters/postgresql/index.ts";
import { openPgSchema, type PgSchema } from "../../support/pg.ts";

class User extends Model.define({
  id: { type: "integer", null: false },
  email: { type: "string", null: false },
}) {
  static table = "users";
}

class Post extends Model.define({
  id: { type: "integer", null: false },
  userId: { type: "integer", null: false },
  title: { type: "string", null: false },
}) {
  static table = "posts";
}

class Product extends Model.define({
  id: { type: "integer", null: false },
  name: { type: "string", null: false },
  priceCents: { type: "integer", null: false },
}) {
  static table = "products";
}

class Code extends Model.define({
  id: { type: "integer", null: false },
  code: { type: "string", null: false },
}) {
  static table = "deferred_codes";
}

// Attributes the database types more narrowly than the Model: Postgres checks the value.
class Ticket extends Model.define({
  id: { type: "integer", null: false },
  token: "string",
  mood: "string",
  feeling: "string",
  seats: "integer",
}) {
  static table = "tickets";
}

// What Postgres's errors say where D1's can't (the constraint-tables allowed difference, #269).
describe("the PostgreSQL adapter's constraint errors", () => {
  let schema: PgSchema;

  beforeAll(async () => {
    schema = await openPgSchema();
  });
  beforeAll(async () => {
    // Checked at COMMIT, not at the INSERT: the batch's transaction ends by failing.
    await schema.pool.query({
      text:
        "CREATE TABLE deferred_codes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
        "code TEXT NOT NULL, UNIQUE (code) DEFERRABLE INITIALLY DEFERRED)",
    });
    await schema.pool.query({ text: "CREATE TYPE mood AS ENUM ('calm')" });
    await schema.pool.query({ text: `CREATE TYPE "Feeling" AS ENUM ('calm')` });
    await schema.pool.query({
      text:
        "CREATE TABLE tickets (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
        'token UUID, mood mood, feeling "Feeling", seats INTEGER)',
    });
  });
  afterAll(() => schema.dispose());
  afterEach(async () => {
    await schema.pool.query({ text: "DELETE FROM posts" });
    await schema.pool.query({ text: "DELETE FROM users" });
  });

  test("a batch's foreign-key failure names its table and columns, even when it writes to several", async () => {
    const db = connect(schema.url);

    const error: unknown = await db
      .batch([
        db.model(User).toInsert({ id: 1, email: "a@example.com" }),
        db.model(Post).toInsert({ userId: 99, title: "Orphan" }),
      ])
      .catch((caught: unknown) => caught);

    expect(error).toBeInstanceOf(InvalidForeignKey);
    expect(error).toMatchObject({ table: "posts", columns: ["user_id"], attributes: ["userId"] });
  });

  // Postgres's detail says "Key (email)=(…)" or "Failing row contains (…)": a log would hold the row.
  test.each([
    [
      "a unique failure",
      RecordNotUnique,
      (db: Database) => db.model(User).create({ email: "kept-secret@example.com" }),
    ],
    [
      "a check failure",
      CheckViolation,
      (db: Database) => db.model(Product).create({ name: "kept-secret", priceCents: -1 }),
    ],
  ])("%s's error, and onQuery's, hold no row's values", async (_, kind, write) => {
    const heard: unknown[] = [];
    const db = connect(schema.url, { onQuery: (event) => heard.push(event.error) });
    await db.model(User).create({ email: "kept-secret@example.com" });

    const error: unknown = await write(db).catch((caught: unknown) => caught);

    expect(error).toBeInstanceOf(kind);
    for (const shown of [error, ...heard]) {
      expect(inspect(shown, { depth: 5 })).not.toContain("kept-secret");
    }
  });

  test("a unique failure names its columns", async () => {
    const db = connect(schema.url);
    await db.model(User).create({ email: "twice@example.com" });

    const error: unknown = await db
      .model(User)
      .create({ email: "twice@example.com" })
      .catch((caught: unknown) => caught);

    expect(error).toMatchObject({ table: "users", columns: ["email"], attributes: ["email"] });
  });
  test("a failure at a batch's COMMIT holds no row's values, and names its columns", async () => {
    const heard: unknown[] = [];
    const db = connect(schema.url, { onQuery: (event) => heard.push(event.error) });
    const codes = db.model(Code);

    const error: unknown = await db
      .batch([codes.toInsert({ code: "kept-secret" }), codes.toInsert({ code: "kept-secret" })])
      .catch((caught: unknown) => caught);

    expect(error).toBeInstanceOf(RecordNotUnique);
    expect(error).toMatchObject({ columns: ["code"] });
    for (const shown of [error, ...heard]) {
      expect(inspect(shown, { depth: 5 })).not.toContain("kept-secret");
    }
  });
  // Postgres's data errors (SQLSTATE class 22) repeat the value they refused, in the message.
  test.each([
    ["uuid", { token: "kept-secret" }, "uuid"],
    ["enum", { mood: "kept-secret" }, "enum mood"],
    ["enum with a quoted name", { feeling: "kept-secret" }, 'enum "Feeling"'],
    ["integer out of range", { seats: 99_999_999_999 }, "out of range for type integer"],
  ])(
    "%s: a refused value's error, and onQuery's, hold no value but name the type",
    async (_, values, named) => {
      const heard: unknown[] = [];
      const db = connect(schema.url, { onQuery: (event) => heard.push(event.error) });

      const errors: unknown[] = [
        await db
          .model(Ticket)
          .findBy(values)
          .catch((caught: unknown) => caught),
        await db
          .model(Ticket)
          .create(values)
          .catch((caught: unknown) => caught),
      ];

      expect((errors[0] as Error).message).toContain(named);
      for (const shown of [...errors, ...heard]) {
        expect(inspect(shown, { depth: 5 })).not.toMatch(/kept-secret|99999999999/);
      }
    },
  );
});
