import { afterAll, afterEach, beforeAll, describe, expect, test } from "vite-plus/test";
import { column, Model, sql } from "../../../packages/arbor/src/index.ts";
import { connect, type QueryEvent } from "../../../packages/arbor/src/adapters/postgresql/index.ts";
import { openPgSchema, type PgSchema } from "../../support/pg.ts";

class User extends Model.define({
  id: { type: "integer", null: false },
  email: { type: "string", null: false },
  age: "integer",
}) {
  static table = "users";
}

class JsonValue extends Model.define({ id: { type: "integer", null: false }, value: "json" }) {
  static table = "json_values";
}

// A text foreign key to an integer key, which Postgres links by the key's digits.
// What Postgres gives that D1 can't: bigints, and its own detail for onQuery (#269).
describe("the PostgreSQL adapter's values", () => {
  let schema: PgSchema;
  const events: QueryEvent[] = [];
  const users = () => connect(schema.url, { onQuery: (event) => events.push(event) }).model(User);

  beforeAll(async () => {
    schema = await openPgSchema();
  });
  afterAll(() => schema.dispose());
  afterEach(async () => {
    events.length = 0;
    await schema.pool.query({ text: "DELETE FROM users" });
    await schema.pool.query({ text: "DELETE FROM json_values" });
    await schema.pool.query({ text: "DELETE FROM samples" });
  });

  test("a bigint reads as a number while it's a safe integer", async () => {
    const age = Number.MAX_SAFE_INTEGER;
    await schema.pool.query({
      text: "INSERT INTO users (id, email, age) VALUES (1, 'a@example.com', $1)",
      values: [age],
    });

    expect((await users().find(1)).age).toBe(age);
  });

  test("a bigint past a safe integer fails when it's read, naming the attribute", async () => {
    await schema.pool.query({
      text: "INSERT INTO users (id, email, age) VALUES (1, 'a@example.com', 9007199254740993)",
    });

    await expect(users().find(1)).rejects.toThrow(
      new TypeError('User: 9007199254740993 isn\'t an integer for "age"'),
    );
    await expect(users().pluck("age")).rejects.toThrow(TypeError);
  });

  test("a ? in an sql fragment's text is Postgres's own, not a placeholder: jsonb's key test", async () => {
    const values = connect(schema.url).model(JsonValue);
    await values.insertAll([
      { id: 1, value: { theme: "dark" } },
      { id: 2, value: { size: 3 } },
    ]);

    const themed = await values.where(sql`${column("value")} ? ${"theme"}`).pluck("id");

    expect(themed).toEqual([1]);
  });

  test("its SQL reads the same with standard_conforming_strings off", async () => {
    const url = new URL(schema.url);
    url.searchParams.set(
      "options",
      `${url.searchParams.get("options")} -c standard_conforming_strings=off`,
    );
    const db = connect(url.toString());
    // Bulk rows name their columns with escape strings, which read the same either way.
    await db.model(User).insertAll([{ id: 7, email: "a@example.com" }]);

    expect((await db.model(User).find(7)).email).toBe("a@example.com");
  });

  test("onQuery hears Postgres's command and row count as meta", async () => {
    await users().create({ email: "a@example.com" });
    await users().pluck("email");

    expect(events.map(({ meta }) => meta)).toEqual([
      { command: "INSERT", rowCount: 1 },
      { command: "SELECT", rowCount: 1 },
    ]);
  });
});

class Amount extends Model.define({
  id: { type: "integer", null: false },
  value: "decimal",
  price: "decimal",
}) {
  static table = "amounts";
}

// Postgres's numeric is exact, and writes its scale's zeros (#391).
describe("the PostgreSQL adapter's decimals", () => {
  let schema: PgSchema;
  const amounts = () => connect(schema.url).model(Amount);

  beforeAll(async () => {
    schema = await openPgSchema();
    await schema.pool.query({
      text: "CREATE TABLE amounts (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value NUMERIC(40, 20), price NUMERIC(10, 2))",
    });
  });
  afterAll(() => schema.dispose());

  test("a decimal keeps every digit, without the scale's trailing zeros", async () => {
    const { id } = await amounts().create({ value: "12345678901234567890.12345678901234567890" });
    const { rows } = await schema.pool.query({ text: "SELECT value::text FROM amounts" });

    const { value } = await amounts().find(id);

    expect(rows[0]!["value"]).toBe("12345678901234567890.12345678901234567890");
    expect(value).toBe("12345678901234567890.1234567890123456789");
  });

  test("a column's scale rounds a created value, which the record then holds", async () => {
    const amount = await amounts().create({ price: "1.555" });

    expect(amount.price).toBe("1.56");
  });

  test("an updated value keeps its digits until it's reloaded", async () => {
    const amount = await amounts().create({ price: "1" });

    await amount.update({ price: "2.345" });

    expect(amount.price).toBe("2.345");
    expect((await amounts().find(amount.id)).price).toBe("2.35");
  });
});

// A table named like one of Postgres's own types, which a cast to its row type would find first.
class Point extends Model.define({
  id: { type: "integer", null: false },
  label: "string",
  shape: "json",
  notes: "json",
}) {
  static table = "point";
}

// Bulk rows are read into the table's row type, which is named as a table (#626).
describe("the PostgreSQL adapter's bulk writes to a table named like a Postgres type", () => {
  let schema: PgSchema;
  const points = () => connect(schema.url).model(Point);

  beforeAll(async () => {
    schema = await openPgSchema();
    // A column named like its table, which a query of the table would read before its row.
    await schema.pool.query({
      text: "CREATE TABLE point (id BIGINT PRIMARY KEY, label TEXT, point TEXT, shape JSONB, notes JSON)",
    });
  });
  afterAll(() => schema.dispose());
  afterEach(() => schema.pool.query({ text: "DELETE FROM point" }));

  test("insertAll writes its rows", async () => {
    await points().insertAll([
      { id: 1, label: "north" },
      { id: 2, label: "south" },
    ]);

    expect(await points().order({ id: "asc" }).pluck("label")).toEqual(["north", "south"]);
  });

  test("insertAll writes json to json and jsonb columns as JSON, not as strings of it", async () => {
    await points().insertAll([{ id: 1, shape: { sides: 3 }, notes: ["tall"] }]);

    const { shape, notes } = await points().find(1);

    expect({ shape, notes }).toEqual({ shape: { sides: 3 }, notes: ["tall"] });
  });

  test("upsertAll inserts a new row and updates one it finds by its key (guard)", async () => {
    await points().insert({ id: 1, label: "north", shape: { sides: 3 } });

    await points().upsertAll([
      { id: 1, label: "east", shape: { sides: 4 } },
      { id: 2, label: "west", shape: { sides: 5 } },
    ]);

    const rows = await points().order({ id: "asc" }).pluck("label", "shape");
    expect(rows).toEqual([
      ["east", { sides: 4 }],
      ["west", { sides: 5 }],
    ]);
  });
});
