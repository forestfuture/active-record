import { spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import pg from "pg";
import { afterAll, describe, expect, test, vi } from "vite-plus/test";
import type { Migration, SchemaResult } from "../../../packages/active-record/cli/for-adapters.ts";
import { cli } from "../../../packages/pg-record/cli/plugin.ts";
import { scratchDirs } from "../../support/scratch.ts";

const scratch = scratchDirs();

// PGlite starts for each schema read, which takes seconds with coverage on.
const pgliteTimeout = { timeout: 60_000 };

/** Migrations by file name, in the order given. */
const migrations = (files: Record<string, string>): Migration[] =>
  Object.entries(files).map(([name, sql]) => ({ name, sql }));

const read = (files: Record<string, string>): Promise<SchemaResult> =>
  cli.readSchema(migrations(files), { migrationsTable: "schema_migrations" });

/** The tables read, or the errors joined, for short assertions. */
async function tablesOf(files: Record<string, string>) {
  const result = await read(files);
  if (!result.ok) throw new Error(result.errors.join("\n"));
  return result;
}

// Postgres's schema is read from its migrations applied to PGlite, so it needs no server (#285).
describe("Postgres's schema, from its migrations on PGlite", pgliteTimeout, () => {
  test("each column's type, nullability and literal default, in column order", async () => {
    const { tables } = await tablesOf({
      "20261108090503_create_users.sql": `
        CREATE TYPE mood AS ENUM ('happy', 'sad');
        CREATE TABLE users (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          email TEXT NOT NULL,
          name VARCHAR(40) DEFAULT 'it''s',
          age INTEGER DEFAULT -1,
          rank SMALLINT DEFAULT 0,
          score DOUBLE PRECISION DEFAULT 1.5,
          ratio REAL,
          is_admin BOOLEAN NOT NULL DEFAULT false,
          settings JSONB NOT NULL DEFAULT '{"theme": "dark"}',
          payload JSON,
          feeling mood DEFAULT 'happy',
          born_on DATE,
          seen_at TIMESTAMP,
          created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
          "displayName" TEXT
        );`,
    });

    expect(tables).toEqual([
      {
        name: "users",
        exportName: "users",
        primaryKey: "id",
        lastChangedBy: "20261108090503_create_users.sql",
        keyType: "bigint",
        attributes: {
          id: { type: "integer", null: false },
          email: { type: "string", null: false },
          name: { type: "string", default: { literal: "it's" } },
          age: { type: "integer", default: { literal: -1 } },
          rank: { type: "integer", default: { literal: 0 } },
          score: { type: "real", default: { literal: 1.5 } },
          ratio: { type: "real" },
          isAdmin: { type: "boolean", null: false, default: { literal: false } },
          settings: { type: "json", null: false, default: { literal: { theme: "dark" } } },
          payload: { type: "json" },
          feeling: { type: "string", default: { literal: "happy" } },
          bornOn: { type: "datetime" },
          seenAt: { type: "datetime" },
          createdAt: { type: "datetime", null: false },
          displayName: { type: "string", column: "displayName" },
        },
      },
    ]);
  });

  test("a string key is made in code, unless it has a literal default; tables are alphabetical", async () => {
    const { tables } = await tablesOf({
      "1_create.sql": `
        CREATE TABLE posts (id UUID PRIMARY KEY DEFAULT gen_random_uuid(), title TEXT);
        CREATE TABLE codes (code TEXT PRIMARY KEY DEFAULT 'none');`,
    });

    expect(tables.map((table) => [table.name, table.attributes])).toEqual([
      ["codes", { code: { type: "string", null: false, default: { literal: "none" } } }],
      [
        "posts",
        { id: { type: "string", null: false, generateId: true }, title: { type: "string" } },
      ],
    ]);
  });

  test("each table is last changed by the migration that changed its columns or constraints", async () => {
    const { tables } = await tablesOf({
      "1_create.sql": `
        CREATE TABLE users (id BIGINT PRIMARY KEY);
        CREATE TABLE posts (id BIGINT PRIMARY KEY);`,
      "2_add_email.sql": "ALTER TABLE users ADD COLUMN email TEXT;",
      "3_index.sql": "CREATE INDEX index_posts_on_id ON posts (id);",
      "4_unique.sql": "ALTER TABLE posts ADD CONSTRAINT one_id UNIQUE (id);",
    });

    expect(tables.map((table) => [table.name, table.lastChangedBy])).toEqual([
      ["posts", "4_unique.sql"],
      ["users", "2_add_email.sql"],
    ]);
  });

  test("leaves out the migrations table, views, and other schemas' tables", async () => {
    const { tables } = await tablesOf({
      "1_create.sql": `
        CREATE TABLE schema_migrations (version TEXT PRIMARY KEY);
        CREATE TABLE users (id BIGINT PRIMARY KEY);
        CREATE VIEW active_users AS SELECT id FROM users;
        CREATE SCHEMA audit;
        CREATE TABLE audit.events (id BIGINT PRIMARY KEY);`,
    });

    expect(tables.map((table) => table.name)).toEqual(["users"]);
  });

  test("a type no attribute holds is read as a string, with a note", async () => {
    const result = await tablesOf({
      "1_create.sql": "CREATE TABLE hosts (id BIGINT PRIMARY KEY, address INET);",
    });

    expect(result.tables[0]!.attributes.address).toEqual({ type: "string" });
    expect(result.notes).toEqual([
      "hosts.address: is inet, so it's read as a string; override it in its Model if it holds another type",
    ]);
  });

  test("numeric, bytea and array columns, and a table without one primary key, are errors", async () => {
    const result = await read({
      "1_create.sql": `
        CREATE TABLE items (
          id BIGINT PRIMARY KEY,
          price NUMERIC(10, 2),
          photo BYTEA,
          tags TEXT[]
        );
        CREATE TABLE logs (line TEXT);
        CREATE TABLE pairs (a BIGINT, b BIGINT, PRIMARY KEY (a, b));`,
    });

    expect(result).toEqual({
      ok: false,
      errors: [
        "items.price: numeric loses precision as a number; store money as integer cents (price_cents BIGINT)",
        "items.photo: bytea columns aren't supported yet (#20)",
        "items.tags: arrays (text[]) aren't supported; use a jsonb column, or a table",
        "logs: no primary key; pg-record needs one (id UUID PRIMARY KEY, or id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)",
        "pairs: a composite primary key (a, b) isn't supported; give the table a single key",
      ],
    });
  });

  test("a migration may create an extension PGlite has its own build of", async () => {
    const { tables } = await tablesOf({
      "1_extensions.sql": `
        CREATE EXTENSION IF NOT EXISTS citext;
        CREATE EXTENSION "uuid-ossp";
        create extension if not exists "pg_trgm" with schema public;`,
      "2_create_users.sql": `
        CREATE TABLE users (id UUID PRIMARY KEY DEFAULT uuid_generate_v4(), email CITEXT NOT NULL);
        CREATE INDEX index_users_on_email ON users USING gin (email gin_trgm_ops);`,
    });

    expect(tables[0]!.attributes).toEqual({
      id: { type: "string", null: false, generateId: true },
      email: { type: "string", null: false },
    });
  });

  test("a migration Postgres refuses is named by its file", async () => {
    const result = await read({
      "1_create.sql": "CREATE TABLE users (id BIGINT PRIMARY KEY);",
      "2_broken.sql": "ALTER TABLE nowhere ADD COLUMN email TEXT;",
    });

    expect(result).toEqual({
      ok: false,
      errors: ['2_broken.sql: relation "nowhere" does not exist'],
    });
  });
});

// An extension PGlite can't load is read on the server schemaUrl names, if it names one (#285).
describe("Postgres's schema, when PGlite can't load an extension", pgliteTimeout, () => {
  const url = process.env["DATABASE_URL"]!;
  const needsDblink = {
    "1_extensions.sql": "CREATE EXTENSION IF NOT EXISTS dblink;",
    "2_create_links.sql": "CREATE TABLE links (id BIGINT PRIMARY KEY, target TEXT NOT NULL);",
  };

  /** The temporary databases left on the server. */
  async function leftOver(): Promise<unknown[]> {
    const client = new pg.Client({ connectionString: url });
    await client.connect();
    try {
      const { rows } = await client.query({
        text: "SELECT datname FROM pg_database WHERE datname LIKE 'active_record_schema_%'",
      });
      return rows;
    } finally {
      await client.end();
    }
  }

  test("is read in a database of its own on the schemaUrl's server, dropped afterwards", async () => {
    const before = await leftOver();

    const result = await cli.readSchema(migrations(needsDblink), {
      migrationsTable: "schema_migrations",
      entry: { schemaUrl: url },
    });

    expect(result).toMatchObject({
      ok: true,
      tables: [{ name: "links", lastChangedBy: "2_create_links.sql" }],
      notes: [
        expect.stringMatching(
          /^PGlite can't load the extension dblink, so the schema was read on .+ in a database of its own$/,
        ),
      ],
    });
    expect(await leftOver()).toEqual(before);
  });

  test("Ctrl-C while it's read there drops the temporary database before the command exits", async () => {
    const before = await leftOver();
    const script = join(scratch("pg-signal-"), "read.mjs");
    const plugin = new URL("../../../packages/pg-record/cli/plugin.ts", import.meta.url).pathname;
    writeFileSync(
      script,
      `import { cli } from ${JSON.stringify(plugin)};
      await cli.readSchema(
        [{ name: "1.sql", sql: "CREATE EXTENSION IF NOT EXISTS dblink;" }, { name: "2.sql", sql: "SELECT pg_sleep(60);" }],
        { entry: { schemaUrl: process.env.SCHEMA_URL } },
      );`,
    );
    const child = spawn(process.execPath, [script], {
      env: { ...process.env, SCHEMA_URL: url },
      stdio: "ignore",
    });
    const exited = new Promise((resolve) => child.on("exit", (_, signal) => resolve(signal)));
    await expect
      .poll(async () => (await leftOver()).length, { timeout: 20_000 })
      .toBe(before.length + 1);

    child.kill("SIGINT");

    expect(await exited).toBe("SIGINT");
    expect(await leftOver()).toEqual(before);
  });

  test("a schemaUrl from the environment is read from it", async () => {
    vi.stubEnv("SCHEMA_DATABASE_URL", url);
    afterAll(() => void vi.unstubAllEnvs());

    const result = await cli.readSchema(migrations(needsDblink), {
      entry: { schemaUrl: "${SCHEMA_DATABASE_URL}" },
    });

    expect(result.ok).toBe(true);
  });

  test("a schemaUrl Node can't read as a URL is refused before any database is made, never printed", async () => {
    const before = await leftOver();

    const result = await cli.readSchema(migrations(needsDblink), {
      entry: { schemaUrl: "postgres://app:s3cret@/active_record_test" },
    });

    expect(result).toEqual({
      ok: false,
      errors: [
        "Couldn't read the schema on localhost: the database's schemaUrl can't be read as a URL; write it as postgres://user:password@host/database",
      ],
    });
    expect(JSON.stringify(result)).not.toContain("s3cret");
    expect(await leftOver()).toEqual(before);
  });

  test("without a schemaUrl, says to set one, and never uses the database's url", async () => {
    const before = await leftOver();

    expect(await cli.readSchema(migrations(needsDblink), { entry: { url } })).toEqual({
      ok: false,
      errors: [
        "1_extensions.sql: PGlite can't load the extension dblink; set the database's schemaUrl in active-record.jsonc to a Postgres server that has it, where the schema is read in a database of its own",
      ],
    });
    expect(await leftOver()).toEqual(before);
  });

  test("what a migration does outside its database is rolled back, a role included", async () => {
    const role = `schema_role_${process.pid}`;
    const files = { ...needsDblink, "3_role.sql": `CREATE ROLE ${role};` };

    expect((await cli.readSchema(migrations(files), { entry: { schemaUrl: url } })).ok).toBe(true);

    const client = new pg.Client({ connectionString: url });
    await client.connect();
    try {
      const { rows } = await client.query({
        text: "SELECT 1 FROM pg_roles WHERE rolname = $1",
        values: [role],
      });
      expect(rows).toEqual([]);
    } finally {
      await client.end();
    }
  });

  test("a schemaUrl naming a variable that isn't set says so", async () => {
    const result = await cli.readSchema(migrations(needsDblink), {
      entry: { schemaUrl: "${NOT_SET_ANYWHERE}" },
    });

    expect(result).toEqual({
      ok: false,
      errors: ["The database's schemaUrl names ${NOT_SET_ANYWHERE}, which isn't set"],
    });
  });
});
