import { describe, expect, test } from "vite-plus/test";
import { parseColumns } from "../../packages/active-record/cli/generate/columns.ts";
import { cli } from "../../packages/pg-record/cli/plugin.ts";

/** The SQL pg-record's plugin writes for a migration, or its error. */
function sqlFor(
  name: string,
  args: string[] = [],
  keys: Record<string, string> = {},
  options: { integerId?: boolean; timestamps?: boolean } = {},
) {
  const parsed = parseColumns(args);
  if (!parsed.ok) throw new Error(parsed.errors.join("\n"));
  const result = cli.migration({
    name,
    columns: parsed.columns,
    keys: new Map(Object.entries(keys)),
    options,
  });
  return result.ok ? result : result.error;
}

// The generators' SQL on Postgres (#285): its own types, and its keys.
describe("pg-record's migrations, for g model and g migration", () => {
  test("a table: a UUID key, each type, defaults, NOT NULL, indexes, and timestamps", () => {
    expect(
      sqlFor("CreateProducts", [
        "name:string!",
        "sku:string:unique",
        "stock:integer=0",
        "price:real=1.5",
        "active:boolean!=true",
        "released_at:datetime:index",
        "settings:json",
        "note:string=it's",
      ]),
    ).toEqual({
      ok: true,
      sql: `CREATE TABLE products (
  id UUID PRIMARY KEY,
  name TEXT NOT NULL,
  sku TEXT,
  stock BIGINT DEFAULT 0,
  price DOUBLE PRECISION DEFAULT 1.5,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  released_at TIMESTAMPTZ,
  settings JSONB,
  note TEXT DEFAULT 'it''s',
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX index_products_on_sku ON products (sku);
CREATE INDEX index_products_on_released_at ON products (released_at);
`,
    });
  });

  test("--id integer is an identity key, and --no-timestamps leaves out the timestamps", () => {
    expect(
      sqlFor("CreateOrders", ["total:integer"], {}, { integerId: true, timestamps: false }),
    ).toEqual({
      ok: true,
      sql: "CREATE TABLE orders (\n  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  total BIGINT\n);\n",
    });
  });

  test("a reference takes its table's key type, or a UUID with a note when the table isn't there yet", () => {
    expect(
      sqlFor(
        "CreateLineItems",
        ["order:references", "user:references"],
        { orders: "bigint" },
        { timestamps: false },
      ),
    ).toEqual({
      ok: true,
      sql: `CREATE TABLE line_items (
  id UUID PRIMARY KEY,
  order_id BIGINT NOT NULL REFERENCES orders (id),
  user_id UUID NOT NULL REFERENCES users (id)
);
CREATE INDEX index_line_items_on_order_id ON line_items (order_id);
CREATE INDEX index_line_items_on_user_id ON line_items (user_id);
`,
      notes: ["users isn't in the migrations yet, so user_id is UUID"],
    });
  });

  test("names Postgres reserves are quoted", () => {
    expect(
      sqlFor("CreateUsers", ["order:integer", "user:string"], {}, { timestamps: false }),
    ).toEqual({
      ok: true,
      sql: 'CREATE TABLE users (\n  id UUID PRIMARY KEY,\n  "order" BIGINT,\n  "user" TEXT\n);\n',
    });
    expect(sqlFor("CreateUser")).toMatchObject({
      sql: expect.stringMatching(/^CREATE TABLE users /),
    });
    expect(sqlFor("AddOrderToCarts", ["order:integer"])).toEqual({
      ok: true,
      sql: 'ALTER TABLE carts ADD COLUMN "order" BIGINT;\n',
    });
  });

  test("adds columns, NOT NULL ones without a default too, and a reference that can be NULL", () => {
    expect(
      sqlFor("AddSkuToProducts", ["sku:string!:unique", "user:references"], { users: "uuid" }),
    ).toEqual({
      ok: true,
      sql: `ALTER TABLE products ADD COLUMN sku TEXT NOT NULL;
ALTER TABLE products ADD COLUMN user_id UUID REFERENCES users (id);
CREATE UNIQUE INDEX index_products_on_sku ON products (sku);
CREATE INDEX index_products_on_user_id ON products (user_id);
`,
    });
  });

  test("removes columns, which drops their indexes with them", () => {
    expect(sqlFor("RemoveSkuFromProducts", ["sku", "user:references"])).toEqual({
      ok: true,
      sql: "ALTER TABLE products DROP COLUMN sku;\nALTER TABLE products DROP COLUMN user_id;\n",
    });
  });

  test("any other name is an empty migration, which takes no columns", () => {
    expect(sqlFor("BackfillPrices")).toEqual({
      ok: true,
      sql: "-- Write the migration's SQL here.\n",
    });
    expect(sqlFor("BackfillPrices", ["price"])).toBe(
      "BackfillPrices: columns only go with Create…, Add…To… or Remove…From… migrations",
    );
    expect(sqlFor("AddSkuToProducts")).toBe(
      "AddSkuToProducts: name the columns to add (sku:string)",
    );
  });
});
