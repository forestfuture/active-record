import { afterEach, beforeEach, describe, expect, test, vi } from "vite-plus/test";
import { planGenerate } from "../../packages/active-record/cli/generate/command.ts";
import { filesOf, linesOf, type Plan } from "../../packages/active-record/cli/plan.ts";
import { planSchema } from "../../packages/active-record/cli/schema/command.ts";
import type {
  DatabaseSnapshot,
  ProjectSnapshot,
} from "../../packages/active-record/cli/project/snapshot.ts";
import type { ProjectAdapter } from "../../packages/active-record/cli/adapter.ts";
import { cli } from "../../packages/d1-record/cli/plugin.ts";

// Migrations are named for the UTC second they're written in, so the clock is set.
beforeEach(() => {
  vi.useFakeTimers({ toFake: ["Date"] });
  vi.setSystemTime(new Date("2026-11-08T09:05:03Z"));
});
afterEach(() => {
  vi.useRealTimers();
});

const cwd = "/app";

/** A plan as what it writes (paths), what it prints, and its exit code. */
function shown(plan: Plan) {
  return { files: filesOf(plan).map((file) => file.path), lines: linesOf(plan), code: plan.code };
}

/** A project with one database, `DB`, as `readProject` would read it from disk. */
function project(database: Partial<DatabaseSnapshot> = {}): ProjectSnapshot {
  return {
    adapter: { ...cli, databases: () => ({ ok: false, error: "unused" }) },
    cwd,
    files: new Map(),
    databases: [
      {
        target: {
          database: {
            binding: "DB",
            migrationsDir: "migrations",
            entry: { binding: "DB" },
          },
          configFile: `${cwd}/wrangler.jsonc`,
          configDir: cwd,
          migrationsDir: `${cwd}/migrations`,
          out: `${cwd}/src/db/schema.ts`,
          base: { path: `${cwd}/src/models/application-record.ts`, className: "ApplicationRecord" },
        },
        migrations: [{ name: "0001_users.sql", sql: "CREATE TABLE users (id TEXT PRIMARY KEY);" }],
        schemaFolder: false,
        hasBase: false,
        nestedMigrations: false,
        toolsFound: [],
        models: [],
        modelErrors: [],
        ...database,
      },
    ],
  };
}

describe("planSchema: what active-record schema writes and prints, from a snapshot", () => {
  test("a new project gets its schema and its base class", async () => {
    const plan = await planSchema(project(), false);

    expect(filesOf(plan).map((file) => file.path)).toEqual([
      `${cwd}/src/db/schema.ts`,
      `${cwd}/src/models/application-record.ts`,
    ]);
    expect(linesOf(plan)).toEqual([
      "Wrote src/db/schema.ts (1 table) from migrations/",
      "Wrote src/models/application-record.ts",
    ]);
    expect(plan.code).toBe(0);
  });

  test("a schema file d1-record didn't write is left alone, and nothing is written", async () => {
    const plan = await planSchema(project({ schema: "export const users = {};\n" }), false);

    expect(filesOf(plan)).toEqual([]);
    expect(linesOf(plan)).toEqual([
      'src/db/schema.ts wasn\'t written by active-record schema (it has no "Generated by" header), ' +
        "so it's left as it is; choose another file with --out, such as --out src/db/active-record.ts",
      "Kept src/db/schema.ts as it was",
    ]);
    expect(plan.code).toBe(1);
  });

  test("a missing migrations folder writes nothing", async () => {
    const plan = await planSchema(project({ migrations: undefined }), false);

    expect(linesOf(plan)).toEqual([
      "No migrations folder at migrations/",
      "Wrote nothing to src/db/schema.ts",
    ]);
    expect(plan.code).toBe(1);
  });

  test("with check, an up-to-date schema passes and nothing is written", async () => {
    const written = filesOf(await planSchema(project(), false))[0]!.source;
    const plan = await planSchema(project({ schema: written, hasBase: true }), true);

    expect(shown(plan)).toEqual({ files: [], lines: ["src/db/schema.ts is up to date"], code: 0 });
  });

  test("lists the Models found, adding each one's attributes to its class", async () => {
    const user = { className: "User", table: "users", file: `${cwd}/src/models/user.ts` };

    const source = filesOf(await planSchema(project({ models: [user] }), false))[0]!.source;

    expect(source).toContain('  models: { User: "users" },');
    expect(source).toContain('declare module "../models/user" {\n  interface User extends');
  });

  test("a Model file that can't be read writes nothing, and keeps the last good file", async () => {
    const error = "Couldn't load src/models/user.ts: Unexpected token";

    const plan = await planSchema(
      project({ schema: "// schema: 0123456789ab\n", modelErrors: [error] }),
      false,
    );

    expect(shown(plan)).toEqual({
      files: [],
      lines: [error, "Kept src/db/schema.ts as it was"],
      code: 1,
    });
  });

  test("with check, a Model the schema doesn't list makes it out of date", async () => {
    const written = filesOf(await planSchema(project(), false))[0]!.source;
    const user = { className: "User", table: "users", file: `${cwd}/src/models/user.ts` };

    const plan = await planSchema(
      project({ schema: written, hasBase: true, models: [user] }),
      true,
    );

    expect(shown(plan)).toEqual({
      files: [],
      lines: ["src/db/schema.ts is out of date: run `active-record schema`"],
      code: 1,
    });
  });

  test("Drizzle's config files earn its notes with a new schema", async () => {
    const plan = await planSchema(project({ toolsFound: ["Drizzle"] }), false);

    expect(linesOf(plan).at(-1)).toMatch(/^Note: these migrations look like Drizzle's\./);
  });
});

describe("planGenerate: what g model and g migration write and print, from a snapshot", () => {
  const product = { kind: "model", name: "Product", columns: ["name:string!"] } as const;

  test("g model writes its migration, its Model, the schema, and the base class", async () => {
    const plan = await planGenerate(project(), product);

    expect(filesOf(plan).map((file) => file.path)).toEqual([
      `${cwd}/migrations/20261108090503_create_products.sql`,
      `${cwd}/src/models/product.ts`,
      `${cwd}/src/db/schema.ts`,
      `${cwd}/src/models/application-record.ts`,
    ]);
    expect(linesOf(plan)).toEqual([
      "Wrote migrations/20261108090503_create_products.sql",
      "Wrote src/models/product.ts",
      "Wrote src/db/schema.ts (2 tables) from migrations/",
      "Wrote src/models/application-record.ts",
      "Next: npx active-record migrate",
    ]);
    expect(plan.code).toBe(0);
  });

  test("a Model file that already exists is refused, and nothing is written", async () => {
    const existing = {
      ...project(),
      files: new Map([[`${cwd}/src/models/product.ts`, "// mine\n"]]),
    };
    const plan = await planGenerate(existing, product);

    expect(shown(plan)).toEqual({
      files: [],
      lines: ["src/models/product.ts already exists", "Wrote nothing"],
      code: 1,
    });
  });

  test("a schema file d1-record didn't write is refused before anything else", async () => {
    const plan = await planGenerate(project({ schema: "export {};\n" }), {
      ...product,
      columns: ["x:nope"],
    });

    expect(filesOf(plan)).toEqual([]);
    expect(linesOf(plan)[0]).toMatch(/^src\/db\/schema.ts wasn't written by active-record schema/);
    expect(linesOf(plan).at(-1)).toBe("Wrote nothing");
  });

  test("a Model already in the one Models file is refused", async () => {
    const models = `${cwd}/src/models.ts`;
    const existing = {
      ...project(),
      files: new Map([[models, "export class Product extends ApplicationRecord {}\n"]]),
    };
    const plan = await planGenerate(existing, { ...product, models: "src/models.ts" });

    expect(linesOf(plan)).toEqual(["src/models.ts already has Product", "Wrote nothing"]);
  });

  test("a schema file that would take over a folder's imports is refused", async () => {
    const plan = await planGenerate(project({ schemaFolder: true }), product);

    expect(linesOf(plan)[0]).toMatch(
      /^src\/db\/schema.ts would take over imports of the folder src\/db\/schema\//,
    );
    expect(plan.code).toBe(1);
  });

  test("a --database the config doesn't bind is refused, naming the bindings it has", async () => {
    expect(shown(await planGenerate(project(), { ...product, database: "CACHE" }))).toEqual({
      files: [],
      lines: ["No database is bound as CACHE; this config has DB"],
      code: 1,
    });
  });

  test("a migration that migrations_pattern wouldn't match is refused", async () => {
    const one = project().databases[0]!;
    const nested = {
      ...one,
      target: {
        ...one.target,
        database: { ...one.target.database, migrationsPattern: "migrations/*/migration.sql" },
      },
    };
    const plan = await planGenerate({ ...project(), databases: [nested] }, product);

    expect(linesOf(plan)).toEqual([
      "migrations/20261108090503_create_products.sql wouldn't match migrations_pattern " +
        "(migrations/*/migration.sql) in wrangler.jsonc, so it wouldn't be applied; write the " +
        "migration with your migration tool instead",
    ]);
  });

  test("the new migration is checked in the order Wrangler applies them", async () => {
    const plan = await planGenerate(
      project({
        migrations: [{ name: "init.sql", sql: "CREATE TABLE users (id TEXT PRIMARY KEY);" }],
      }),
      { kind: "migration", name: "AddSkuToUsers", columns: ["sku"] },
    );

    // 20261108090503_add_sku_to_users.sql sorts before init.sql, so Wrangler would run it first, and fail.
    expect(filesOf(plan)).toEqual([]);
    expect(plan.code).toBe(1);
    expect(linesOf(plan).at(-1)).toBe("Wrote nothing");
  });
});

// The core plans with whatever adapter the project uses (#278): a stand-in here, not D1's plugin.
describe("planning with another adapter's plugin", () => {
  const readSchemas: string[][] = [];
  const stub: ProjectAdapter = {
    name: "stub",
    init: () => undefined,
    databases: () => ({ ok: false, error: "unused" }),
    async readSchema(migrations) {
      readSchemas.push(migrations.map((migration) => migration.name));
      const id = { type: "string", null: false } as const;
      const tables = migrations.map((migration) => ({
        name: migration.name.replace(/^\d+_|\.sql$/g, ""),
        exportName: "items",
        primaryKey: "id",
        lastChangedBy: migration.name,
        attributes: { id },
      }));
      return { ok: true, tables, notes: [], textDates: [] };
    },
    migration: () => ({ ok: true, sql: "-- stub\n" }),
    remote: () => "unused",
    stateFolder: () => "unused",
    open: async () => "unused",
    migrate: async () => 0,
  };

  test("the schema comes from the plugin's tables", async () => {
    const plan = await planSchema({ ...project(), adapter: stub }, false);

    expect(linesOf(plan)[0]).toBe("Wrote src/db/schema.ts (1 table) from migrations/");
    expect(readSchemas.at(-1)).toEqual(["0001_users.sql"]);
  });

  test("a migration is the plugin's SQL in a file the command names, checked by reading the schema it makes", async () => {
    const product = { kind: "model", name: "Product", columns: ["name:string!"] } as const;

    const plan = await planGenerate({ ...project(), adapter: stub }, product);

    expect(filesOf(plan).find((file) => file.path.endsWith("_create_products.sql"))).toEqual({
      path: `${cwd}/migrations/20261108090503_create_products.sql`,
      source: "-- stub\n",
    });
    expect(readSchemas.at(-1)).toEqual(["0001_users.sql", "20261108090503_create_products.sql"]);
  });

  // The adapter's factory has the adapter's name, exported from its package (#284).
  test("the schema imports the adapter's factory from its package, and calls it with the binding", async () => {
    const plan = await planSchema({ ...project(), adapter: { ...stub, name: "pg" } }, false);
    const source = filesOf(plan)[0]!.source;

    expect(source).toContain('import { pg } from "@forestfuture/pg-record";');
    expect(source).toContain('adapter: pg({ binding: "DB" }),');
    // As a word: a fingerprint is hex, and can hold "d1".
    expect(source).not.toMatch(/\bd1\b/);
  });

  // An adapter without a pattern setting can't be told to read migrations in folders (#284).
  test("migrations in folders are noted as unread, when the plugin has no pattern setting", async () => {
    const plan = await planSchema({ ...project({ nestedMigrations: true }), adapter: stub }, false);

    expect(linesOf(plan).at(-1)).toBe(
      "Note: migrations/ has its migrations in folders, as Drizzle writes them, which aren't read",
    );
  });

  test("a migration a pattern wouldn't match is refused, when the plugin names no setting for it", async () => {
    const one = project().databases[0]!;
    const pattern = "migrations/*/migration.sql";
    const database = { ...one.target.database, migrationsPattern: pattern };
    const nested = { ...one, target: { ...one.target, database } };
    const product = { kind: "model", name: "Product", columns: [] } as const;

    const plan = await planGenerate({ ...project(), databases: [nested], adapter: stub }, product);

    expect(linesOf(plan)).toEqual([
      "migrations/20261108090503_create_products.sql wouldn't match the pattern " +
        "(migrations/*/migration.sql) in wrangler.jsonc, so it wouldn't be applied; write the " +
        "migration with your migration tool instead",
    ]);
  });

  test("--check reports a schema written for another adapter as out of date", async () => {
    const written = await planSchema({ ...project(), adapter: { ...stub, name: "d1" } }, false);
    const schema = filesOf(written)[0]!.source;

    const plan = await planSchema(
      { ...project({ schema }), adapter: { ...stub, name: "pg" } },
      true,
    );

    expect(shown(plan)).toEqual({
      files: [],
      lines: ["src/db/schema.ts is out of date: run `active-record schema`"],
      code: 1,
    });
  });
});
