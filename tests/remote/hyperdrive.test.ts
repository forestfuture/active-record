import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import pg from "pg";
import { afterAll, beforeAll, describe, expect, test } from "vite-plus/test";

/**
 * pg-record through a real Hyperdrive (#269), which local mode can't show: it pools connections.
 * It needs CLOUDFLARE_ACCOUNT_ID, CLOUDFLARE_API_TOKEN, PG_SMOKE_HYPERDRIVE_ID (a Hyperdrive
 * config) and PG_SMOKE_DATABASE_URL (the Postgres it reaches, for setting up), as
 * docs/agents/remote-smoke.md says. Without them it's skipped.
 */
const configured = [
  "CLOUDFLARE_ACCOUNT_ID",
  "CLOUDFLARE_API_TOKEN",
  "PG_SMOKE_HYPERDRIVE_ID",
  "PG_SMOKE_DATABASE_URL",
].every((name) => process.env[name] !== undefined);

const wrangler = new URL("../../node_modules/.bin/wrangler", import.meta.url).pathname;
const worker = new URL("hyperdrive/worker.ts", import.meta.url).pathname;

type Pool = InstanceType<typeof pg.Pool>;

/** Tables of runs that crashed before cleaning up, older than an hour: `smoke_<time>_<tag>_…`. */
async function dropStale(pool: Pool): Promise<void> {
  const { rows } = await pool.query({
    text: "SELECT tablename FROM pg_tables WHERE schemaname = 'public' AND tablename LIKE 'smoke\\_%'",
  });
  const before = Date.now() - 60 * 60 * 1000;
  for (const { tablename } of rows as { tablename: string }[]) {
    const time = Number.parseInt(/^smoke_([0-9a-z]+)_/.exec(tablename)?.[1] ?? "", 36);
    if (time < before) await pool.query({ text: `DROP TABLE IF EXISTS "${tablename}" CASCADE` });
  }
}

const account = process.env["CLOUDFLARE_ACCOUNT_ID"];

/** Workers of runs killed before they deleted theirs, older than an hour: `pg-record-smoke-<tag>`. */
async function deleteStaleWorkers(): Promise<void> {
  const response = await fetch(
    `https://api.cloudflare.com/client/v4/accounts/${account}/workers/scripts`,
    { headers: { authorization: `Bearer ${process.env["CLOUDFLARE_API_TOKEN"]}` } },
  );
  const { result } = (await response.json()) as { result: { id: string; created_on: string }[] };
  const before = Date.now() - 60 * 60 * 1000;
  for (const { id, created_on: created } of result) {
    if (!id.startsWith("pg-record-smoke-") || Date.parse(created) >= before) continue;
    execFileSync(wrangler, ["delete", "--name", id, "--force"], { stdio: "ignore" });
  }
}

describe.runIf(configured)("pg-record through a real Hyperdrive", { timeout: 120_000 }, () => {
  const tag = Math.random().toString(36).slice(2, 6);
  const prefix = `smoke_${Date.now().toString(36)}_${tag}_`;
  const name = `pg-record-smoke-${tag}`;
  const directory = mkdtempSync(join(tmpdir(), "pg-record-smoke-"));
  // The Worker is public while the run lasts: it answers only requests with this run's token.
  const token = randomUUID();
  let pool: Pool;
  let url: string;

  const get = async (path: string) => {
    const response = await fetch(new URL(path, url), { headers: { "x-smoke-token": token } });
    const body = (await response.json()) as Record<string, unknown>;
    expect(body["error"]).toBeUndefined();
    return body;
  };

  beforeAll(async () => {
    pool = new pg.Pool({ connectionString: process.env["PG_SMOKE_DATABASE_URL"]! });
    await dropStale(pool);
    await deleteStaleWorkers();
    await pool.query({
      text: `CREATE TABLE ${prefix}users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT NOT NULL UNIQUE, role TEXT)`,
    });
    const config = join(directory, "wrangler.jsonc");
    writeFileSync(
      config,
      JSON.stringify({
        name,
        main: worker,
        compatibility_date: "2025-09-01",
        compatibility_flags: ["nodejs_compat"],
        account_id: account,
        workers_dev: true,
        hyperdrive: [{ binding: "HYPERDRIVE", id: process.env["PG_SMOKE_HYPERDRIVE_ID"] }],
        vars: { TABLE_PREFIX: prefix, SMOKE_TOKEN: token },
      }),
    );
    const deployed = execFileSync(wrangler, ["deploy", "--config", config], { encoding: "utf8" });
    url = /https:\/\/\S+\.workers\.dev/.exec(deployed)![0];
  }, 300_000);
  afterAll(async () => {
    execFileSync(wrangler, ["delete", "--name", name, "--force"], { stdio: "ignore" });
    await pool?.query({ text: `DROP TABLE IF EXISTS ${prefix}users` });
    await pool?.end();
    rmSync(directory, { recursive: true, force: true });
  });

  test("a Model's statics use the binding's own database", async () => {
    expect(await get("/statics")).toEqual({ email: "statics@example.com" });
  });

  test("a request's database serves its scope, and a page's count and rows read in order", async () => {
    expect(await get("/scope")).toEqual({ emails: ["a@example.com"], total: 2, heard: 3 });
  });

  test("a write beside a failing batch is kept, and the batch writes nothing (ADR-0017)", async () => {
    expect(await get("/batch")).toEqual({
      batch: "RecordNotUnique",
      emails: ["beside@example.com"],
    });
  });
});
